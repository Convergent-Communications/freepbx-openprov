<?php
namespace FreePBX\modules\Openprov;

/**
 * Generates and installs the provisioning Apache vhost (DESIGN.md D3).
 * Installing needs root; everything else is read-only.
 */
class WebServer
{
	public const CONF = '/etc/apache2/sites-available/openprov.conf';
	public const LINK = '/etc/apache2/sites-enabled/openprov.conf';

	public function __construct(private Settings $settings, private string $webRoot)
	{
	}

	public function config(): string
	{
		$root = rtrim($this->webRoot, '/');
		$https = (int) $this->settings->get('https_port');
		$http = (int) $this->settings->get('http_port');
		$cert = (string) $this->settings->get('tls_cert');
		$key = (string) $this->settings->get('tls_key');
		$chain = (string) $this->settings->get('tls_chain');
		// Directory sections merge shortest path first, so a server-wide
		// "AllowOverride All" on /var/www/html beats "<Directory />". Disable
		// .htaccess on every ancestor explicitly (vhost-scoped).
		$ancestors = '';
		for ($d = dirname($root); $d !== '/' && $d !== '.'; $d = dirname($d)) {
			$ancestors = "  <Directory $d>\n    AllowOverride None\n  </Directory>\n" . $ancestors;
		}
		$body = function () use ($root, $ancestors) {
			return <<<CONF
  DocumentRoot $root
  SetEnv OPENPROV_VHOST 1
  RewriteEngine On
  RewriteRule ^ $root/prov.php [END]
  # The module lives under /admin, whose .htaccess only whitelists FreePBX's
  # own entry points. Ignore .htaccess files for this vhost only.
$ancestors  <Directory $root>
    Options None
    AllowOverride None
    Require all granted
  </Directory>
  # Phones send Basic auth; mod_php exposes it as PHP_AUTH_USER/PW.
  LimitRequestBody 65536
  ErrorLog \${APACHE_LOG_DIR}/openprov_error.log
  CustomLog \${APACHE_LOG_DIR}/openprov_access.log combined

CONF;
		};
		$out = "# Generated by OpenProv (fwconsole openprov web --install). Do not edit;\n# change settings with fwconsole openprov settings and re-run the install.\n";
		if ($https > 0) {
			$out .= "Listen $https\n<VirtualHost *:$https>\n" . $body()
				. "  SSLEngine on\n  SSLCertificateFile $cert\n  SSLCertificateKeyFile $key\n"
				. ($chain !== '' ? "  SSLCertificateChainFile $chain\n" : '')
				. "  SSLProtocol all -SSLv3 -TLSv1 -TLSv1.1\n"
				. "</VirtualHost>\n";
		}
		if ($http > 0) {
			$out .= "Listen $http\n<VirtualHost *:$http>\n" . $body() . "</VirtualHost>\n";
		}
		return $out;
	}

	public function status(): array
	{
		$installed = is_file(self::CONF) ? (string) file_get_contents(self::CONF) : null;
		return [
			'installed' => $installed !== null,
			'enabled' => is_link(self::LINK) || is_file(self::LINK),
			'current' => $installed !== null && trim($installed) === trim($this->config()),
			'https_port' => (int) $this->settings->get('https_port'),
			'http_port' => (int) $this->settings->get('http_port'),
			'cert_readable' => is_readable((string) $this->settings->get('tls_cert')),
			'running_as_root' => function_exists('posix_geteuid') && posix_geteuid() === 0,
			'command' => 'fwconsole openprov web --install',
		];
	}

	/** Write, enable, test and reload. Returns [ok, message]. */
	public function install(): array
	{
		if (!function_exists('posix_geteuid') || posix_geteuid() !== 0) {
			return [false, 'Run as root: fwconsole openprov web --install'];
		}
		$https = (int) $this->settings->get('https_port');
		if ($https > 0 && !is_readable((string) $this->settings->get('tls_cert'))) {
			return [false, 'TLS certificate not readable: ' . $this->settings->get('tls_cert')];
		}
		$previous = is_file(self::CONF) ? file_get_contents(self::CONF) : null;
		file_put_contents(self::CONF, $this->config());
		@symlink(self::CONF, self::LINK);
		foreach (['ssl', 'rewrite', 'env'] as $mod) {
			exec('a2enmod -q ' . escapeshellarg($mod) . ' 2>&1');
		}
		exec('apache2ctl configtest 2>&1', $out, $rc);
		if ($rc !== 0) {
			if ($previous === null) {
				@unlink(self::LINK);
				@unlink(self::CONF);
			} else {
				file_put_contents(self::CONF, $previous);
			}
			return [false, "apache2ctl configtest failed; change rolled back:\n" . implode("\n", $out)];
		}
		exec('systemctl reload apache2 2>&1', $out2, $rc2);
		return [$rc2 === 0, $rc2 === 0 ? 'Provisioning web server installed' : implode("\n", $out2)];
	}

	public function uninstall(): array
	{
		if (!function_exists('posix_geteuid') || posix_geteuid() !== 0) {
			return [false, 'Run as root'];
		}
		@unlink(self::LINK);
		@unlink(self::CONF);
		exec('systemctl reload apache2 2>&1', $out, $rc);
		return [$rc === 0, 'removed'];
	}
}
